assert.match(webApp, /MapPin,/, "Diary explored stat should use MapPin icon");
assert.match(webApp, /stat-card \$\{active \? "active" : ""\}/, "Diary stat cards should expose active state");
assert.match(webApp, /unit="LOGS"/, "Total logs stat should show LOGS unit");
assert.match(webApp, /unit="BARS"/, "Explored stat should show BARS unit");
assert.match(webApp, /unit="PTS"/, "Avg rating stat should show PTS unit");
