assert.match(webApp, /auth-register-field/, "web auth should always reserve register field space");
assert.match(webApp, /Enter with Google/, "web auth should show an Enter with Google button");
assert.match(webApp, /startGoogleAuth/, "web auth should start Google OAuth through the auth API");
assert.match(webStyles, /\.auth-screen[\s\S]*grid-template-rows:/, "web auth screen should pin the brand and card rows");
assert.match(webStyles, /\.brand-block[\s\S]*height:/, "web auth brand block should have fixed height");
